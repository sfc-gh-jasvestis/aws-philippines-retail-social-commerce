-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT creator.ID AS ENTITY_ID, creator.NAME AS ENTITY_NAME,
       creator.REGION, creator.CATEGORY, creator.RISK_TIER, creator.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.ORDER_COUNT) AS ORDER_COUNT,
       SUM(observation.GMV_PHP) AS GMV_PHP,
       SUM(observation.ISSUE_COUNT) AS ISSUE_COUNT,
       SUM(observation.RTS_COUNT) AS RTS_COUNT,
       SUM(observation.LATE_DELIVERY) AS LATE_DELIVERY_COUNT,
       SUM(observation.CATALOG_SYNC_DUE) AS CATALOG_SYNC_DUE,
       SUM(observation.CATALOG_SYNC_DONE) AS CATALOG_SYNC_DONE,
       100.0 * (SUM(observation.ORDER_COUNT) - SUM(observation.ISSUE_COUNT)) / NULLIF(SUM(observation.ORDER_COUNT), 0) AS CLEAN_ORDER_PCT,
       100.0 * SUM(observation.RTS_COUNT) / NULLIF(SUM(observation.ISSUE_COUNT), 0) AS ISSUE_RTS_PCT,
       100.0 * SUM(observation.CATALOG_SYNC_DONE) / NULLIF(SUM(observation.CATALOG_SYNC_DUE), 0) AS CATALOG_SYNC_PCT,
       AVG(observation.RETURN_RATE_PCT) AS AVG_RETURN_RATE_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.CREATOR_DAILY observation
JOIN RAW.CREATORS creator ON creator.ID = observation.ENTITY_ID
GROUP BY creator.ID, creator.NAME, creator.REGION, creator.CATEGORY, creator.RISK_TIER, creator.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(ORDER_COUNT) AS ORDER_COUNT, SUM(GMV_PHP) AS GMV_PHP,
       SUM(ISSUE_COUNT) AS ISSUE_COUNT, SUM(RTS_COUNT) AS RTS_COUNT,
       100.0 * SUM(RTS_COUNT) / NULLIF(SUM(ISSUE_COUNT), 0) AS ISSUE_RTS_PCT
FROM RAW.CREATOR_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.ISSUE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ISSUE_TYPE, SUM(ISSUE_COUNT) AS ISSUE_COUNT,
       SUM(RTS_COUNT) AS RTS_COUNT,
       SUM(LATE_DELIVERY) AS LATE_DELIVERY_COUNT,
       SUM(GMV_PHP) AS EXPOSED_GMV_PHP,
       100.0 * SUM(RTS_COUNT) / NULLIF(SUM(ISSUE_COUNT), 0) AS ISSUE_RTS_PCT
FROM RAW.CREATOR_DAILY
WHERE ISSUE_COUNT > 0
GROUP BY ISSUE_TYPE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(ORDER_COUNT) AS ORDERS, SUM(ISSUE_COUNT) AS ISSUES,
         SUM(RTS_COUNT) AS RTS, SUM(LATE_DELIVERY) AS BREACHES, SUM(GMV_PHP) AS GMV_PHP,
         SUM(CATALOG_SYNC_DUE) AS CATALOG_SYNC_DUE, SUM(CATALOG_SYNC_DONE) AS CATALOG_SYNC_DONE,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.CREATOR_DAILY
), book AS (SELECT COUNT(*) AS CREATOR_COUNT FROM RAW.CREATORS),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.COMPLIANCE_DOCUMENTS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Clean Order Rate' AS TITLE,
         100.0 * (ORDERS - ISSUES) / NULLIF(ORDERS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Order Issues Raised', ISSUES, '' FROM observations
  UNION ALL SELECT 3, 'RTS Orders', RTS, '' FROM observations
  UNION ALL SELECT 4, 'Issue RTS Rate', 100.0 * RTS / NULLIF(ISSUES, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Late Deliveries', BREACHES, '' FROM observations
  UNION ALL SELECT 6, 'GMV (PHP M)', GMV_PHP / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Orders Processed', ORDERS, '' FROM observations
  UNION ALL SELECT 8, 'Catalog Sync Compliance', 100.0 * CATALOG_SYNC_DONE / NULLIF(CATALOG_SYNC_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Creators Monitored', CREATOR_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Compliance Document Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Compliance Documents Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.ISSUE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
